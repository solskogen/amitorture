#!/usr/bin/env python3
"""Generate disk/bench/kernels/kexpect.h, the checksum every bench kernel
must produce, by building each kernel set's sources natively (32-bit, SSE
single-precision floats) and running them once with tools/kset_host.c.

The kernels are portable C and their checksums don't depend on byte order,
so the native result is the reference; tools/kset_sim.py checks that the
68k builds agree under Musashi. The soft-float sets use IEEE single
precision, as SSE does. A set with FP flags (k020f, built for a 6888x/040/
060 FPU with FPCR at single precision) is built for the x87 instead, with
the same flags and the x87 set to single precision: both round every result
to a single's mantissa but keep the extended exponent range in registers,
so they agree with each other and not always with SSE.

  kset_expect.py [-o FILE]       (default: stdout)

Needs a host C/C++ compiler that can build 32-bit code (cc -m32).
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DISK = os.path.join(ROOT, "disk")
K = os.path.join(DISK, "bench", "kernels")
SETS = ["k000", "k020", "k020f", "k020s"]
CC = os.environ.get("HOST_CC", "cc")
CXX = os.environ.get("HOST_CXX", "c++")
FLAGS = ["-m32", "-O2", "-msse2", "-mfpmath=sse", "-ffp-contract=off",
         "-fno-strict-aliasing", "-w", "-DNDEBUG"]


def set_info(name):
    out = subprocess.run(["make", "-s", "-C", DISK, f"kset-info-{name}"],
                         check=True, capture_output=True, text=True).stdout
    info = {}
    for line in out.splitlines():
        key, _, val = line.partition(":")
        info[key.strip()] = val.split()
    return info


def ndk_include():
    tc = os.environ.get("AMIGA_TOOLCHAIN", "/opt/amiga/bin")
    return os.environ.get("NDK_INCLUDE", os.path.join(tc, "..", "m68k-amigaos", "ndk-include"))


def run_set(name, tmp):
    info = set_info(name)
    defs = info["defs"]
    fp = info.get("fp", [])
    flags = FLAGS
    if fp:
        flags = [f for f in FLAGS if f not in ("-msse2", "-mfpmath=sse")] + \
            ["-mfpmath=387"] + fp
        defs = defs + ["-DKSET_HOST_X87_SINGLE"]
    inc = [f"-I{K}/inc", f"-I{K}", f"-I{ndk_include()}", f"-I{K}/third_party/zlib",
           f"-I{K}/third_party/amissl/shim", "-DZ_SOLO",
           "-Dmalloc=k_malloc", "-Dfree=k_free"]
    objs = []
    for src in info["c"]:
        if src == "softfloat.c":
            continue
        obj = os.path.join(tmp, name + "_" + src.replace("/", "_") + ".o")
        extra = ["-DSTANDALONE_"] if "freetype/" in src else []
        subprocess.run([CC] + flags + defs + inc + extra + ["-c", os.path.join(K, src), "-o", obj],
                       check=True)
        objs.append(obj)
    for src in info["cxx"]:
        obj = os.path.join(tmp, name + "_" + src.replace("/", "_") + ".o")
        subprocess.run([CXX] + flags + defs + ["-std=c++17", "-fno-exceptions", "-fno-rtti",
                                               f"-I{K}", "-c", os.path.join(K, src), "-o", obj],
                       check=True)
        objs.append(obj)
    drv = os.path.join(tmp, name + "_host.o")
    subprocess.run([CC] + flags + defs + inc + ["-c", os.path.join(ROOT, "tools", "kset_host.c"),
                                                "-o", drv], check=True)
    exe = os.path.join(tmp, name)
    subprocess.run([CXX, "-m32"] + objs + [drv, "-o", exe], check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    return [tuple(line.split()) for line in out.splitlines()]


def generate():
    lines = [
        "/* Generated by tools/kset_expect.py; do not edit.",
        " * The checksum of every kernel, per kernel set, in the set's order. */",
        "#ifndef AMT_KEXPECT_H",
        "#define AMT_KEXPECT_H",
        "",
        "struct kexpect {",
        "    const char *name;",
        "    unsigned long check;",
        "};",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for s in SETS:
            rows = run_set(s, tmp)
            lines.append("")
            lines.append(f"static const struct kexpect kexpect_{s}[] = {{")
            for name, check in rows:
                if not re.fullmatch(r"[0-9a-f]{8}", check):
                    raise SystemExit(f"{s}/{name}: bad checksum {check!r}")
                lines.append(f'    {{"{name}", 0x{check}UL}},')
            lines.append("};")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--output")
    a = ap.parse_args(argv)
    text = generate()
    if a.output:
        with open(a.output, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
