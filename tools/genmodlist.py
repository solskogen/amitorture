#!/usr/bin/env python3
"""Generate the module table from AMT_MODULE(...) lines in disk/modules/*.c.

usage: genmodlist.py OUT.c MODULE.c...
       genmodlist.py --names MODULE.c...   (print module names)
Fails on duplicate ids or names, ids outside 0..63, or malformed lines.
"""
import re, sys

pat = re.compile(r'^AMT_MODULE\(\s*([A-Za-z_]\w*)\s*,\s*(\d+)\s*,')
names_only = sys.argv[1] == "--names"
mods = []
for path in sys.argv[2:]:
    with open(path) as f:
        for ln, line in enumerate(f, 1):
            if line.startswith('AMT_MODULE('):
                m = pat.match(line)
                if not m:
                    sys.exit(f"{path}:{ln}: malformed AMT_MODULE line")
                mods.append((int(m.group(2)), m.group(1), f"{path}:{ln}"))
ids, names = {}, {}
for i, n, where in mods:
    if not 0 <= i <= 63:
        sys.exit(f"{where}: module id {i} outside 0..63")
    if i in ids:
        sys.exit(f"{where}: module id {i} also used at {ids[i]}")
    if n in names:
        sys.exit(f"{where}: module name {n} also used at {names[n]}")
    ids[i], names[n] = where, where
mods.sort()
if names_only:
    print(" ".join(n for _, n, _ in mods))
    sys.exit(0)
with open(sys.argv[1], 'w') as o:
    o.write('/* generated by tools/genmodlist.py - do not edit */\n#include "mod.h"\n')
    for i, n, _ in mods:
        o.write(f'extern const struct amt_module amt_mod_{n};\n')
    o.write('const struct amt_module *const amt_modules[] = {\n')
    for i, n, _ in mods:
        o.write(f'    &amt_mod_{n},\n')
    o.write('    0\n};\n')
    o.write(f'const int amt_n_modules = {len(mods)};\n')
