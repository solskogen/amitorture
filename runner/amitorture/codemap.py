def jit_backend_files():
    """The JIT code generator files of this host (aarch64: the ARM64 backend)."""
    a = jit_arch()
    if a == "arm" and platform.machine().lower() in ("aarch64", "arm64"):
        return [("jit/arm/compemu_midfunc_arm64.cpp", "mid-level ops (EA arithmetic, e.g. arm_ADD_ldiv8)"),
                ("jit/arm/compemu_midfunc_arm64_2.cpp", "mid-level ops, part 2"),
                ("jit/arm/codegen_arm64.cpp", "ARM64 instruction emitters"),
                ("jit/arm/compemu_arm.cpp", "compiled handlers op_<opcode>_0_comp_ff/_nf (generated)"),
                ("jit/arm/compemu_support_arm.cpp", "block compiler, fault recovery")]
    if a == "arm":
        return [("jit/arm/compemu_midfunc_arm.cpp", "mid-level ops"), ("jit/arm/codegen_arm.cpp", "ARM emitters"),
                ("jit/arm/compemu_arm.cpp", "compiled handlers")]
    return [("jit/x86/compemu_midfunc_x86.cpp", "mid-level ops"), ("jit/x86/codegenx86.h", "x86 emitters"),
            ("jit/x86/compemu_x86.cpp", "compiled handlers")]


def _jit_subsystems():
    a = jit_arch()
    sup = f"jit/{a}/compemu_support_{a}.cpp"
    return {
        "smc": [(sup, "flush_icache_hard", "translation cache flush"),
                (sup, "invalidate_block", "block invalidation"),
                (sup, "check_checksum", "self-modifying code detection")],
        "flags": [(f"jit/{a}/flags_{a}.h", None, "flag handling (comp_nf)")],
        "_compile": [(sup, "compile_block", "JIT block compiler")],
    }


def pointers(item, options, src=None):
    """Code pointers for one failure item (case_fail / engine_mismatch)."""
    o = options or {}
    mod = (item.get("mod") or "").lower()
    out = []

    def add(f, func, why, conf="hint"):
        if src is not None and not os.path.isfile(os.path.join(src.path, f)):
            return                       # not in this tree (e.g. no PCem): do not send the reader there
        p = {"file": f"src/{f}", "function": func, "why": why, "confidence": conf}
        if src is not None and func:
            p["line"] = src.line_of(f, func)
            if p["line"] is None:
                p["function"] = None
                p["why"] = f"{why} (look for {func})"
        out.append(p)

    ct = core_table(o)
    jit = ct["jit"]
    rec = item.get("record") or item.get("twin") or item.get("ref") or {}
    op = opcode_from(item.get("ctx"), item.get("in"), (rec or {}).get("ctx"), (rec or {}).get("in"))
    if op is not None:
        h = handler(op, o, src)
        if h.get("function"):
            out.append({"file": h.get("file"), "function": h["function"], "line": h.get("line"),
                        "why": f"interpreter handler for opcode {op:04x}"
                               + (f" ({h['mnemonic']})" if h.get("mnemonic") else "") + f", {h['core']} core",
                        "confidence": h.get("confidence")})
        else:
            out.append({"file": None, "function": None, "why": h.get("confidence"), "confidence": "hint"})
        if h.get("jit", {}).get("function"):
            j = h["jit"]
            out.append({"file": j["file"], "function": j["function"], "line": j.get("line"),
                        "why": f"JIT compiled handler for {op:04x}"
                               + (f" (or {j['nf_variant']} with dead flags)" if j.get("nf_variant") else ""),
                        "confidence": j.get("confidence")})
    elif mod in ("cpu_basic", "flags", "exceptions", "smc") and ct.get("table") is not None:
        out.append({"file": f"src/{ct['file']}", "function": None,
                    "why": f"CPU core {ct['table_name']} ({ct['mode_name']}); no opcode in ctx to name the handler",
                    "confidence": "hint"})
    if mod == "fpu" or (op is not None and (op & 0xf000) == 0xf000):
        sf = _true(o.get("fpu_softfloat", "false"))
        if sf:
            add("fpp_softfloat.cpp", "to_exten", "softfloat value conversion")
            add("softfloat/softfloat.cpp", None, "softfloat arithmetic")
        else:
            add("fpp_native.cpp", "fp_to_exten", "native (host double) value conversion")
            add("fpp_native.cpp", "fp_from_exten", "native (host double) value conversion")
        if jit and _true(o.get("compfpu", "true")):
            arch = jit_arch()
            add(f"jit/{arch}/compemu_fpp_{arch}.cpp", None, "JIT FPU (compfpu=true)")
    for f, func, why in SUBSYSTEMS.get(mod, []):
        if mod == "fpu" and func is None:
            continue
        add(f, func, why)
    if jit:
        js = _jit_subsystems()
        for f, func, why in js.get(mod, []):
            add(f, func, why)
        if item.get("kind") == "engine_mismatch" or item.get("jit_only"):
            for f, func, why in js["_compile"]:
                add(f, func, why + " (engine mismatch)")
            for f, why in jit_backend_files():
                add(f, None, f"JIT backend of this host ({platform.machine()}): {why}")
    if _true(o.get("cpu_threaded", "false")) and mod in ("interrupts", "timing", "cia"):
        add("newcpu.cpp", "m68k_run_2_020", "threaded CPU main loop")
    # drop line lookups that failed so a reader is not sent to a wrong place
    for p in out:
        if p.get("line") is None:
            p.pop("line", None)
    return out
