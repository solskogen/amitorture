"""Where to look in Amiberry for a failure (hints, labelled as such).

CPU core selection follows src/newcpu.cpp build_cpufunctbl():

    lvl  = (cpu_model - 68000) / 10, 68060 -> 5
    mode = JIT on (cachesize>0): 1 if comp_trustbyte=direct else 2
                                 (interpreter fallback handlers used by the JIT)
           else MMU:  7 cycle-exact, 6 compatible, 5 fast
           else       4 cycle-exact, 3 compatible, 0 fast
    tbl  = cputbls[lvl][mode]  (op_smalltbl_<N>)

Handlers are generated by gencpu as op_<opcode>_<N>_ff (flags) in
cpuemu_<file>.cpp; identical handlers are shared between tables, so the
function's <N> is not always the table's: the exact name comes from the
table itself in cpustbl.cpp ({ op_xxxx_N_ff, ..., 0xOPCODE, ... } /* MNEMO */).
Opcodes that differ only in register fields share the handler of the lowest
opcode of their group (readcpu.cpp handle_merges). With the JIT on, compiled
code comes from jit/<arch>/compemu_<arch>.cpp op_<opcode>_0_comp_ff/_nf
(compstbl_<arch>.cpp); opcodes without a compiled handler run the
interpreter fallback table above.

docs/emulator-map/amiberry.md describes the same mapping for a human/AI reader.
"""
from __future__ import annotations

import os
import platform
import re

# cputbls[lvl][mode] (src/newcpu.cpp)
CPUTBLS = [
    [5, 45, 55, 12, 14, None, None, None],   # 68000
    [4, 44, 54, 11, 13, None, None, None],   # 68010
    [3, 43, 53, 20, 21, None, None, None],   # 68020
    [2, 42, 52, 22, 23, 32, 34, 35],         # 68030
    [1, 41, 51, 25, 25, 31, 31, 31],         # 68040
    [0, 40, 50, 24, 24, 33, 33, 33],         # 68060
]
MODE_NAMES = {0: "fast (no prefetch emulation)", 1: "JIT fallback interpreter (comp_trustbyte=direct)",
              2: "JIT fallback interpreter (comp_trustbyte indirect)", 3: "compatible (prefetch)",
              4: "cycle-exact", 5: "MMU", 6: "MMU + compatible", 7: "MMU + cycle-exact"}


def handler_file(n):
    """cpuemu file that defines op_xxxx_<n>_ff (gencpu output grouping)."""
    if 0 <= n <= 5:
        return "cpuemu_0.cpp"
    for lo, hi, f in ((11, 12, "cpuemu_11.cpp"), (13, 14, "cpuemu_13.cpp"), (24, 25, "cpuemu_24.cpp"),
                      (40, 49, "cpuemu_40.cpp"), (50, 55, "cpuemu_50.cpp")):
        if lo <= n <= hi:
            return f
    return f"cpuemu_{n}.cpp"


def _true(v):
    return str(v).lower() in ("true", "yes", "1")


def core_table(options):
    """Which CPU core ran, from the (resolved) options."""
    o = options or {}
    cpu = int(o.get("cpu_model", "68000") or 68000)
    jit = int(o.get("cachesize", "0") or 0) > 0
    mmu = str(o.get("mmu_model", "0")) not in ("0", "", "none")
    if "cycle_exact" in o:
        ce_val = str(o.get("cycle_exact")).lower()
        ce = ce_val == "true"
    else:
        ce_val = "true" if _true(o.get("cpu_cycle_exact", "false")) else "false"
        ce = ce_val == "true"
    compat = _true(o.get("cpu_compatible", "false")) or ce_val in ("memory", "true")
    if jit:
        mode = 1 if str(o.get("comp_trustbyte", "direct")) == "direct" else 2
    elif mmu:
        mode = 7 if ce else (6 if compat else 5)
    elif ce:
        mode = 4
    elif compat:
        mode = 3
    else:
        mode = 0
    lvl = (cpu - 68000) // 10
    if lvl == 6:
        lvl = 5
    lvl = max(0, min(5, lvl))
    tbl = CPUTBLS[lvl][mode]
    out = {"cpu_model": cpu, "lvl": lvl, "mode": mode, "mode_name": MODE_NAMES[mode], "table": tbl,
           "table_name": f"op_smalltbl_{tbl}" if tbl is not None else None,
           "file": handler_file(tbl) if tbl is not None else None, "jit": jit,
           "source": "src/newcpu.cpp build_cpufunctbl (cputbls[lvl][mode])"}
    if tbl is None:
        out["note"] = "no core for this combination: Amiberry aborts ('no CPU emulation cores available')"
    if jit:
        arch = jit_arch()
        nf = _true(o.get("comp_nf", "true"))
        out["jit_backend"] = [f for f, _ in jit_backend_files()]
        out["jit_compiled"] = {"file": f"jit/{arch}/compemu_{arch}.cpp",
                               "table": f"jit/{arch}/compstbl_{arch}.cpp op_smalltbl_0_comp_ff"
                                        + (" (+ _comp_nf where flags are dead, comp_nf=true)" if nf else ""),
                               "support": f"jit/compemu_support.cpp, jit/{arch}/compemu_support_{arch}.cpp"}
    if int(o.get("fpu_model", "0") or 0) and cpu < 68020:
        out["fpu_hack"] = "F-line $F200-$F3FF handlers come from op_smalltbl_3 (68020) on 68000/010"
    return out


def jit_arch():
    m = platform.machine().lower()
    return "x86" if m in ("x86_64", "amd64", "i686", "i386") else "arm"


def find_src(binary=None, explicit=None):
    """Amiberry's src/ directory (read-only), if it can be found."""
    cands = []
    if explicit:
        cands.append(explicit)
    if os.environ.get("AMIBERRY_SRC"):
        cands.append(os.environ["AMIBERRY_SRC"])
    if binary:
        d = os.path.dirname(os.path.abspath(binary))
        cands += [os.path.join(d, "..", "src"), os.path.join(d, "src"), os.path.join(d, "..", "..", "src")]
    for c in cands:
        c = os.path.abspath(c)
        if os.path.isfile(os.path.join(c, "newcpu.cpp")):
            return c
    return None


# { handler_ff, handler_ff_noret, opcode, ... } /* MNEMO */ : one of the two is NULL
_TBL_RX = re.compile(r"^\{\s*(NULL|op_[0-9a-f]+_\d+_ff)\s*,\s*(NULL|op_[0-9a-f]+_\d+_ff)\s*,\s*0x([0-9a-f]{4})\s*,"
                     r".*?\}\s*,\s*/\*\s*(\S+)\s*\*/")
_HDR_RX = re.compile(r"^const struct cputbl op_smalltbl_(\d+)\[\]")
_COMP_RX = re.compile(r"\{\s*(op_[0-9a-f]+_\d+_comp_(?:ff|nf))\s*,\s*(\d+)\s*,\s*0x[0-9a-f]+\s*\}\s*,\s*/\*\s*(\S+)\s*\*/")


class Source:
    """Lazy index of an Amiberry source tree."""

    def __init__(self, path):
        self.path = path
        self._tables = None
        self._comp = None
        self._defs = {}

    def rel(self, f):
        return "src/" + f

    def tables(self):
        if self._tables is None:
            self._tables = {}
            p = os.path.join(self.path, "cpustbl.cpp")
            cur = None
            try:
                with open(p, encoding="utf-8", errors="replace") as fh:
                    for line in fh:
                        m = _HDR_RX.match(line)
                        if m:
                            cur = self._tables.setdefault(int(m.group(1)), {})
                            continue
                        if cur is not None:
                            m = _TBL_RX.match(line)
                            if m:
                                func = m.group(1) if m.group(1) != "NULL" else m.group(2)
                                if func != "NULL":
                                    cur[int(m.group(3), 16)] = (func, m.group(4))
            except OSError:
                pass
        return self._tables

    def comp(self):
        if self._comp is None:
            self._comp = {"ff": {}, "nf": {}}
            arch = jit_arch()
            p = os.path.join(self.path, "jit", arch, f"compstbl_{arch}.cpp")
            try:
                with open(p, encoding="utf-8", errors="replace") as fh:
                    for line in fh:
                        for m in _COMP_RX.finditer(line):
                            kind = "ff" if m.group(1).endswith("_ff") else "nf"
                            self._comp[kind].setdefault(int(m.group(2)), (m.group(1), m.group(3)))
            except OSError:
                pass
        return self._comp

    def definitions(self, f):
        """{function name: line} for top-level function definitions in src/f."""
        if f not in self._defs:
            d = {}
            rx = re.compile(r"^[A-Za-z_][\w\s\*:<>,]*?\b([A-Za-z_]\w*)\s*\([^;]*$")
            try:
                with open(os.path.join(self.path, f), encoding="utf-8", errors="replace") as fh:
                    for n, line in enumerate(fh, 1):
                        if line[:1].isspace() or line.startswith(("#", "//", "/*", "}")):
                            continue
                        m = rx.match(line)
                        if m and m.group(1) not in d and m.group(1) not in ("if", "for", "while", "switch", "return"):
                            d[m.group(1)] = n
            except OSError:
                pass
            self._defs[f] = d
        return self._defs[f]

    def line_of(self, f, func):
        return self.definitions(f).get(func)


def _merge_candidates(op):
    seen = []
    for mask in (0x0000, 0x0007, 0x0e00, 0x0e07, 0x00ff, 0x0eff, 0x000f, 0x0e0f, 0x01ff, 0x0fff):
        c = op & ~mask & 0xffff
        if c not in seen:
            seen.append(c)
    return seen


def handler(opcode, options, src=None):
    """The interpreter handler (and the JIT one) that executes `opcode`
    under these options."""
    ct = core_table(options)
    out = {"opcode": f"{opcode:04x}", "table": ct["table_name"], "core": ct["mode_name"]}
    tbl = ct["table"]
    if tbl is None:
        return out
    if src is None:
        out.update({"function": f"op_{opcode:04x}_{tbl}_ff", "file": f"src/{handler_file(tbl)}",
                    "confidence": "guess (no Amiberry source found: the name assumes the table's own handler "
                                  "and the exact opcode; pass --amiberry-src for an exact lookup)"})
    else:
        table = src.tables().get(tbl, {})
        hit = None
        for c in _merge_candidates(opcode):
            if c in table:
                hit = (c, *table[c])
                break
        if hit is None:
            out.update({"function": None, "confidence": f"opcode not in op_smalltbl_{tbl}: illegal/unimplemented "
                                                         "on this CPU (op_illg / op_unimpl, newcpu.cpp)"})
        else:
            c, func, mnemo = hit
            n = int(func.split("_")[2])
            f = handler_file(n)
            line = src.line_of(f, func)
            out.update({"function": func, "mnemonic": mnemo, "file": src.rel(f), "line": line,
                        "confidence": "exact (cpustbl.cpp)" if c == opcode else
                        f"shared handler of opcode {c:04x} (register-field merge, readcpu.cpp handle_merges)"})
    if ct["jit"]:
        arch = jit_arch()
        if src is None:
            out["jit"] = {"function": f"op_{opcode:04x}_0_comp_ff", "nf_variant": f"op_{opcode:04x}_0_comp_nf",
                          "file": f"src/jit/{arch}/compemu_{arch}.cpp", "confidence": "guess"}
        else:
            comp = src.comp()
            j = None
            for c in _merge_candidates(opcode):
                if c in comp["ff"]:
                    j = (c, *comp["ff"][c])
                    break
            if j is None:
                out["jit"] = {"function": None, "note": "no compiled handler: the JIT calls the interpreter "
                                                        f"handler above ({ct['table_name']})"}
            else:
                f = f"jit/{arch}/compemu_{arch}.cpp"
                out["jit"] = {"function": j[1], "nf_variant": j[1].replace("_comp_ff", "_comp_nf"), "file": src.rel(f),
                              "line": src.line_of(f, j[1]),
                              "confidence": "exact (compstbl)" if j[0] == opcode else f"shared with {j[0]:04x}"}
    return out


OPCODE_KEYS = ("op", "opcode", "opc", "insn", "iw", "words", "opcodes", "code", "instr", "ins")


def opcode_from(*objs):
    """First instruction word found in ctx/in objects, or None."""
    def first_word(v):
        if isinstance(v, int):
            return v & 0xffff if v <= 0xffff else (v >> 16) & 0xffff
        if isinstance(v, str):
            m = re.match(r"\s*(?:0x|\$)?([0-9a-fA-F]{4})", v)
            return int(m.group(1), 16) if m else None
        if isinstance(v, list) and v:
            return first_word(v[0])
        return None
    for o in objs:
        if not isinstance(o, dict):
            continue
        for k, v in o.items():
            if str(k).lower() in OPCODE_KEYS:
                w = first_word(v)
                if w is not None:
                    return w
    return None


