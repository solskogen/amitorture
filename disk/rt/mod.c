int amt_board_ok(const struct amt_probe_board *b)
{
    ULONG a, e;
    /* only CDF_SHUTUP (bit 0) disqualifies. CDF_CONFIGME (bit 1) is "this
     * board needs a driver to claim it" (libraries/configvars.h): it is set
     * on every configured board no driver has bound yet, e.g. every RTG or
     * network card at bootblock time. An unconfigured board never gets a
     * valid cd_BoardAddr, which the window checks below reject. */
    if (!b || (b->flags & 1))           /* CDF_SHUTUP */
        return 0;
    a = b->addr;
    if (!a || !b->size)
        return 0;
    e = a + b->size - 1;
    if (e < a)                          /* wraps */
        return 0;
    if (a >= 0x00200000UL && e <= 0x009fffffUL)
        return 1;                       /* Zorro II memory window */
    if (a >= 0x00e90000UL && e <= 0x00efffffUL)
        return 1;                       /* Zorro II I/O window; $E80000-$E8FFFF is the
                                           autoconfig slot, never a configured board */
    if (a >= 0x10000000UL)
        return 1;                       /* Zorro III */
    return 0;
}

