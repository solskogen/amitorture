/* amitorture module runner (CONTRACT.md section 10). See mod.h for the API.
 *
 * Order of a run:
 *   1. allocate the pools (largest chip/any need of the enabled modules) and
 *      the bare-phase stack, while exec is alive;
 *   2. run every enabled AMT_PH_OS module, in id order;
 *   3. wait until disk DMA, the blitter and (CLI start) IDE are idle, or
 *      refuse the takeover (see "takeover guard");
 *      take over: Forbid, Disable, save hardware state, enter supervisor
 *      mode through exec Supervisor() (amt_supervisor_run), install
 *      the catch-all vectors and the autovector dispatchers, switch to our
 *      own stack;
 *   4. run every enabled AMT_PH_BARE module, in id order, each inside
 *      amt_try() with a fresh environment (DMA off except the status
 *      screen's BPLEN|COPEN, see rt/screen.c; INTENA = INTEN|VERTB,
 *      default vectors, SR=$2000, watchdog armed);
 *   5. restore everything and return to main.c, which emits "done".
 */
