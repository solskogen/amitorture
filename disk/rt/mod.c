/* frame counting that works in both phases: count VPOS wraps from the beam */
static ULONG beam_frames_wait_step(ULONG *lastv)
{
    ULONG v = ((ULONG)(CREG(R_VPOSR) & 7) << 8) | (CREG(R_VHPOSR) >> 8);
    ULONG wrapped = v < *lastv;
    *lastv = v;
    return wrapped;
}

int amt_request(const char *what, const char *tag, const char *args_json, ULONG timeout_frames)
{
    static ULONG req_id;
    ULONG id = ++req_id, frames = 0, lastv = 0;
    json_begin("request");
    json_int("id", (long)id);
    json_str("what", what);
    json_str("tag", tag ? tag : "");
    if (args_json)
        json_raw("args", args_json);
    json_end();
    if (!amt_mbox)
        return 0;
    while (amt_mbox->host_ack != id) {
        frames += beam_frames_wait_step(&lastv);
        if (frames > timeout_frames)
            return 0;
        if (bare_active)
            amt_watchdog_kick();
    }
    return 1;
}

