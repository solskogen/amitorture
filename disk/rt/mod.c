static const char *const st_names[] = { "pass", "fail", "skip", "untestable" };

static void count(int st)
{
    switch (st) {
    case AMT_ST_PASS: m_pass++; break;
    case AMT_ST_FAIL: m_fail++; break;
    case AMT_ST_SKIP: m_skip++; break;
    default: m_untestable++; break;
    }
}

void amt_case_open(const char *case_id, int st)
{
    if (st < 0 || st > 3)
        st = AMT_ST_FAIL;
    count(st);
    case_no++;
    mbox_set_pos(cur ? cur->id : 0, case_no);
    json_begin("case");
    json_str("mod", cur ? cur->name : "?");
    json_str("case", case_id);
    json_str("st", st_names[st]);
}

void amt_case_close(void)
{
    json_end();
    if (bare_active)
        amt_watchdog_kick();
    screen_count(cur, m_pass, m_fail, m_skip, m_untestable, amt_n_pass + m_pass, amt_n_fail + m_fail,
                 amt_n_skip + m_skip, amt_n_untestable + m_untestable);
}

void amt_case(const char *case_id, int st, const char *why)
{
    amt_case_open(case_id, st);
    if (st != AMT_ST_PASS)
        json_str("why", why ? why : "(no reason given)");
    amt_case_close();
}

int amt_check32(const char *case_id, const char *what, ULONG expect, ULONG got,
                const char *why)
{
    if (expect == got) {
        amt_case(case_id, AMT_ST_PASS, 0);
        return 1;
    }
    amt_case_open(case_id, AMT_ST_FAIL);
    json_obj("expect");
    json_hex(what, expect);
    json_obj_end();
    json_obj("got");
    json_hex(what, got);
    json_obj_end();
    json_str("why", why);
    amt_case_close();
    return 0;
}

