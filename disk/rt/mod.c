/* Repetitions after the first run. The point is the JIT: Amiberry (like
 * WinUAE) translates a block after 4 executions (compemu_support_*.cpp
 * optcount[0]) and runs the translation from then on, so 100 leaves a 25x
 * margin; more only costs time (minutes on a 7 MHz 68000). */
ULONG amt_hot_reps(void) { return AMT_QUICK() ? 20 : 100; }

long amt_hot(ULONG (*fn)(ULONG iter), ULONG reps, ULONG *first, ULONG *bad)
{
    ULONG f = fn(0), i;
    if (first)
        *first = f;
    for (i = 1; i <= reps; i++) {
        ULONG r = fn(i);
        if (r != f) {
            if (bad)
                *bad = r;
            return (long)i;
        }
        if ((i & 63) == 0)
            amt_watchdog_kick();
    }
    return -1;
}

/* colour clocks per line: 227 (PAL/NTSC short) or 228 (NTSC long line);
 * use 227.5 averaged as 455/2. Lines per frame: PAL 312/313, NTSC 262/263. */
ULONG amt_cck_hz(void)
{
    return amt_probe_result.pal ? 3546895UL : 3579545UL;
}

ULONG amt_eclk_hz(void)
{
    return amt_probe_result.pal ? 709379UL : 715909UL;
}

ULONG amt_ticks(void)
{
    static ULONG last;
    ULONG f1, f2, v, h, t;
    UWORD req;
    ULONG lines = amt_probe_result.pal ? 313 : 263;
    do {
        ULONG b;
        f1 = amt_frames;
        b = amt_beam();
        v = b >> 8;
        h = b & 0xff;
        req = CREG(R_INTREQR);
        f2 = amt_frames;
    } while (f1 != f2);
    /* The beam has wrapped to line 0 but the VERTB handler has not counted
     * the frame yet (interrupts masked, or not serviced yet): count it. */
    if ((req & 0x0020) && v < lines / 2)
        f1++;
    /* colour clocks: frame * lines * 227 + v * 227 + h (approximate across
     * short/long frames); never goes backwards */
    t = (f1 * lines + v) * 227UL + h;
    if ((LONG)(t - last) < 0)
        t = last;
    return last = t;
}

void amt_watchdog_kick(void)
{
    amt_wd_left = wd_limit;
}

amt_vec_fn amt_vec_set(int vec, amt_vec_fn handler)
{
    amt_vec_fn old;
    if (vec < 2 || vec > 63 || !bare_active)
        return 0;
    old = (amt_vec_fn)vbr_tab[vec];
    vbr_tab[vec] = (ULONG)handler;
    return old;
}

