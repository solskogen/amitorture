#define RBUF_OFF 0x1000
#define TBUF_OFF 0x4000
#define BUFSZ    0x600
#define NRING    4                 /* RLEN = TLEN = 2 */
#define LEN_CODE 2

static const UBYTE padr[6] = { 0x02, 0x00, 0x5a, 0xa2, 0x06, 0x05 };   /* locally administered */

static void csr_w(UWORD r, UWORD v)
{
    es_ww(rap, r);
    es_ww(rdp, v);
}
static UWORD csr_r(UWORD r)
{
    es_ww(rap, r);
    return es_rw(rdp);
}
static void ram_ww(ULONG off, UWORD v) { es_ww((volatile UWORD *)(ram + off), v); }
static UWORD ram_rw(ULONG off) { return es_rw((volatile UWORD *)(ram + off)); }

