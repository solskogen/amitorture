/* network: network cards at register level (CONTRACT.md section 10, id 18,
 * disk group "exp").
 *
 * Boards are taken ONLY from amt_probe_result.boards, by known ids:
 *   Commodore A2065   man 514 ($0202) prod 112 ($70)   Am7990 LANCE
 * Board layout (Commodore A2065; same as Linux a2065.c / NetBSD if_le):
 *   board+$4000 RDP (register data port, word), board+$4002 RAP (register
 *   address port, word), board+$8000-$FFFF 32 KB RAM. The LANCE sees that
 *   RAM at chip addresses $8000-$FFFF. Interrupts go to INT2.
 *
 * Expectations come from the AMD Am7990 LANCE data sheet: CSR0 bit
 * semantics (write-1-to-set INIT/STRT/STOP/TDMD, write-1-to-clear
 * BABL/CERR/MISS/MERR/RINT/TINT/IDON, ERR and INTR summaries), STOP
 * clearing CSR0 and CSR3, CSR1-3 accessible while stopped, the init block
 * and descriptor ring formats, the MODE register (LOOP, INTL, DTCR, DTX,
 * DRX), internal loopback (the receiver gets the transmitter's frame; the
 * CRC is generated by the transmitter when DTCR=0, taken from the buffer
 * when DTCR=1, and checked by the receiver) and MCNT including the FCS.
 * Loopback frames are kept at 24/28 bytes (the Am7990 loopback limit is
 * 32 bytes of data).
 *
 *   MNT ZZ9000 (Z2/Z3)  man 28014 ($6D6E) prod 3/4      firmware Ethernet
 * ZZ9000 network ABI (MNT ZZ9000 firmware / ZZ9000Net.device, as emulated
 * by Amiberry zz9000.cpp): board+$80 ETH_TX (write: frame length, transmit
 * the frame in the TX window board+$8000), +$82 ETH_RX (write: serial of
 * the frame to release), +$84/$86/$88 MAC (read/write), +$8C RX status
 * (low byte: frames queued), RX window board+$2000 = length.W, serial.W,
 * frame; +$04 CONFIG: bit 0 Ethernet interrupt enable, write bit 3|bit 4 to
 * acknowledge, read bit 0 = Ethernet interrupt pending. There is no chip
 * data sheet for it and no loopback; only host traffic is tested.
 *
 * External traffic: one ARP request for 10.0.2.2 from 10.0.2.15 (the user
 * mode NAT addresses of Amiberry's "slirp" backend: config a2065=slirp,
 * zz9000_net=slirp). It is a broadcast, and a real LAN host with 10.0.2.15
 * in its ARP cache would update that entry to our MAC (RFC 826 merge
 * rule), so it is sent ONLY when the run says the card is on an emulator
 * backend (run flag AMT_F_NET, set by the runner for slirp entries) or with
 * the unsafe flag; otherwise the ARP cases are untestable (review M4).
 * Only a reply from 10.0.2.2 to 10.0.2.15 counts; other frames are
 * skipped (review M5). If nothing answers, the case is untestable.
 * See docs/cases/network.md. */
